#!/usr/bin/env bash

# Init command implementation

cmd_init() {
    local show_help=false

    # Parse arguments
    while [[ $# -gt 0 ]]; do
        case $1 in
            -h|--help)
                show_help=true
                shift
                ;;
            *)
                print_error "Unknown option: $1"
                echo "Run 'theodo-scan init --help' for usage information."
                exit 1
                ;;
        esac
    done

    # Show help if requested
    if [ "$show_help" = true ]; then
        cat << EOF
Usage: theodo-scan init [options]

Initialize a new Theodo Scan configuration file.

This command creates a .theodorc file in the current directory with
default configuration values. You can edit this file to customize the
settings for your project. If a .gitignore file exists in the current
directory, .theodo/theodo-scan-sbom.json will be added to it.

Options:
    -h, --help          Show this help message

Examples:
    theodo-scan init
    cd my-project && theodo-scan init

EOF
        exit 0
    fi

    # Execute command
    print_header "🔧 Theodo Scan - Init Command"
    echo ""

    # Get current directory name
    local dir_name
    dir_name=$(basename "$PWD")

    # Check if .theodorc already exists
    if [ -f ".theodorc" ]; then
        print_warning "Configuration file .theodorc already exists in this directory."
        echo -n "Do you want to overwrite it? (y/N): "
        read -r response
        echo ""

        if [[ ! "$response" =~ ^[Yy]$ ]]; then
            print_info "Init cancelled. Existing configuration preserved."
            exit 0
        fi

        print_warning "Overwriting existing configuration..."
        echo ""
    fi

    # Create .theodorc file
    cat > .theodorc << EOF
# Theodo Scan Configuration File
# This file contains project-specific configuration for the Theodo Scan CLI tool
# Generated by: theodo-scan init

# Organization name - identifies your organization or team
export THEODO_SCAN_ORG="$dir_name"

# Project name - identifies your specific project
export THEODO_SCAN_PROJECT="$dir_name"

# Component name - identifies which part of your project is being scanned
# Examples: 'frontend', 'backend', 'api-service', 'auth-service', 'main'
# Use this to scan different components of a monorepo or microservices separately
export THEODO_SCAN_COMPONENT="main"

# S3 Bucket name - identifies which AWS S3 bucket the upload command should upload SBOM to
export THEODO_SCAN_BUCKET_NAME="watchtower-prod-s3bucketbucket-ubzdhdmf"

# AWS Profile name for LOCAL runs only - identifies which AWS CLI profile to use when uploading SBOM to S3.
# In CI (when the CI environment variable is set), this value is ignored and the default AWS
# credential chain is used (OIDC-assumed role or AWS_ACCESS_KEY_ID / AWS_SECRET_ACCESS_KEY env vars).
export THEODO_SCAN_LOCAL_AWS_PROFILE="watchtower"
EOF

    # Add .theodo/sbom.json to .gitignore if it exists
    if [ -f ".gitignore" ]; then
        if ! grep -qxF '.theodo/sbom.json' .gitignore; then
            echo '.theodo/sbom.json' >> .gitignore
            print_success "Added .theodo/sbom.json to .gitignore"
        else
            print_info ".theodo/sbom.json already in .gitignore"
        fi
    fi

    # Display success messages
    print_success "Configuration file created: .theodorc"
    echo ""
    print_info "Default values set:"
    print_info "  - THEODO_SCAN_ORG: $dir_name"
    print_info "  - THEODO_SCAN_PROJECT: $dir_name"
    print_info "  - THEODO_SCAN_COMPONENT: main"
    print_info "  - THEODO_SCAN_BUCKET_NAME: watchtower-prod-s3bucketbucket-ubzdhdmf"
    print_info "  - THEODO_SCAN_LOCAL_AWS_PROFILE: watchtower"
    echo ""
    print_info "Please edit .theodorc to customize these values for your project."
}

